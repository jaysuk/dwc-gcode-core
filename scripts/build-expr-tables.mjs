#!/usr/bin/env node
/**
 * Generates `src/expr/tables.ts` — the exact set of RRF expression functions and named constants —
 * from RepRapFirmware's own source, not transcribed by hand. Both lists are defined in ONE place
 * each, as a `NamedEnum(...)` macro invocation in `ExpressionParser.cpp`:
 *
 *   NamedEnum(NamedConstant, unsigned int, _false, iterations, line, _null, pi, _result, _true, input);
 *   NamedEnum(Function, unsigned int, abs, acos, ..., vector);
 *
 * (the `_`-prefixed names are C++ keyword-clash escaping - `_false`/`_null`/`_true`/`_result` are
 * spelled `false`/`null`/`true`/`result` in actual G-code). This script fetches that file at
 * `RRF_BASELINE` via `gh api` (matching `scripts/rrf-triage.mjs`'s convention - portable, no local
 * RRF clone required) and extracts both lines with a regex, so a future baseline bump re-generates
 * the tables from source again rather than drifting from a hand-copied list.
 *
 *   node scripts/build-expr-tables.mjs [--tag 3.7.0-rc.1]
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const REPO = "Duet3D/RepRapFirmware";
const FILE = "src/GCodes/GCodeBuffer/ExpressionParser.cpp";

function gh(args) {
	return execFileSync("gh", ["api", ...args], { encoding: "utf-8", maxBuffer: 16 * 1024 * 1024 });
}

const argv = process.argv.slice(2);
const tagArg = argv.indexOf("--tag");
let tag = tagArg !== -1 ? argv[tagArg + 1] : null;
if (tag === null) {
	const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf-8"));
	tag = pkg.rrf.baseline;
}

const text = gh([`repos/${REPO}/contents/${FILE}?ref=${tag}`, "-H", "Accept: application/vnd.github.raw"]);
const lines = text.split("\n");

function extractNamedEnum(enumName) {
	const lineIndex = lines.findIndex((l) => l.includes(`NamedEnum(${enumName},`));
	if (lineIndex === -1) throw new Error(`NamedEnum(${enumName}, ...) not found in ${FILE}@${tag}`);
	const line = lines[lineIndex];
	const match = /NamedEnum\(\s*\w+\s*,\s*[^,]+,\s*(.+)\)\s*;/.exec(line);
	if (match === null) throw new Error(`Could not parse NamedEnum(${enumName}, ...) line: ${line}`);
	const names = match[1].split(",").map((s) => s.trim().replace(/^_/, ""));
	return { names, line: lineIndex + 1 };
}

const constants = extractNamedEnum("NamedConstant");
const functions = extractNamedEnum("Function");

// A handful of functions need one more operand fetched via a comma (`GetNextOperand`) beyond their
// first (parenthesised) one - read directly from ExpressionParser.cpp's own handling of each
// `case Function::` (atan2, mod, pow, take, drop, find, fileread take 2+; vector takes 2; max/min take
// 1-or-more, either an array or a comma list; exists takes exactly 1, an identifier reference, handled
// as its own special case before the normal argument is even parsed). Recorded here by inspection, not
// derivable from the NamedEnum line alone - if this ever needs to be exact for validation (task 10's
// dictionary does something similar for G/M-code parameters), re-derive from source at that point.
const MULTI_ARG = new Set(["atan2", "mod", "pow", "take", "drop", "find", "fileread", "vector"]);
const VARIADIC = new Set(["max", "min"]);

const out = `/**
 * RRF's expression functions and named constants — generated by \`scripts/build-expr-tables.mjs\`
 * from ${FILE} at RRF ${tag}, \`NamedEnum(NamedConstant, ...)\` (line ${constants.line}) and
 * \`NamedEnum(Function, ...)\` (line ${functions.line}). Do not hand-edit; re-run the script instead.
 *
 * Cross-checked 2026-09-14 against \`@duet3d/monacotokens@3.7.0-rc.1\`'s
 * \`dist/expressions/expressions.json\`: identical function and constant name lists, no discrepancy
 * (see docs/wiki-discrepancies.md).
 */

export const EXPRESSION_FUNCTIONS: ReadonlySet<string> = new Set([
${functions.names.map((n) => `\t"${n}",`).join("\n")}
]);

export const NAMED_CONSTANTS: ReadonlySet<string> = new Set([
${constants.names.map((n) => `\t"${n}",`).join("\n")}
]);

/** Functions that take one required argument BEYOND the first (parenthesised) one, read via a
 *  comma - e.g. \`mod(a, b)\`, \`fileread(path, skip, count, sep)\` (three more). Not a full arity
 *  table (this package doesn't validate call arity - see task 07's "out of scope"); recorded only so
 *  the parser knows to expect a comma after these without erroring on a single-argument call to one
 *  of them, and to keep looping for \`fileread\`'s extra operands. */
export const MULTI_ARG_FUNCTIONS: ReadonlySet<string> = new Set([${[...MULTI_ARG].map((n) => `"${n}"`).join(", ")}]);

/** \`max\`/\`min\`: one array argument, OR two-or-more comma-separated scalar arguments. */
export const VARIADIC_FUNCTIONS: ReadonlySet<string> = new Set([${[...VARIADIC].map((n) => `"${n}"`).join(", ")}]);
`;

writeFileSync(new URL("../src/expr/tables.ts", import.meta.url), out);
console.log(`Wrote src/expr/tables.ts: ${functions.names.length} functions, ${constants.names.length} constants (RRF ${tag}).`);
