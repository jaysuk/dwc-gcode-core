#!/usr/bin/env node
/**
 * Generates `docs/diagnostics.md` from `RULES` (task 14, `docs/tasks/14-diagnostics.md` step 3) -
 * id, severity, description, sources, one table per category. Run after `npm run build` (imports
 * the compiled `dist/diagnostics/rules.js`, not `src/` directly - this is a plain Node script, no
 * TS loader).
 *
 *   npm run build && node scripts/build-diagnostics-doc.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const { RULES } = await import(new URL("../dist/diagnostics/rules.js", import.meta.url));

const CATEGORY_ORDER = ["syntax", "structure", "dictionary", "project", "release", "menu", "data", "objectModel"];
const CATEGORY_TITLE = {
	syntax: "Syntax", structure: "Structure", dictionary: "Dictionary", project: "Project",
	release: "Release", menu: "Menu", data: "Data", objectModel: "Object model",
};

function escapeCell(s) {
	return s.replace(/\|/g, "\\|");
}

let out = "# Diagnostics\n\n";
out += "Generated by `scripts/build-diagnostics-doc.mjs` from `RULES` (`src/diagnostics/rules.ts`, ";
out += "task 14) - do not hand-edit. Every rule cites the RRF source or wiki passage that justifies ";
out += "it; see `docs/tasks/14-diagnostics.md` for what's deliberately NOT implemented and why.\n\n";

for (const category of CATEGORY_ORDER) {
	const rules = RULES.filter((r) => r.category === category);
	if (rules.length === 0) continue;
	out += `## ${CATEGORY_TITLE[category]}\n\n`;
	out += "| id | severity | description | sources |\n";
	out += "| --- | --- | --- | --- |\n";
	for (const r of rules) {
		const sources = r.sources.map((s) => escapeCell(s)).join("<br>");
		out += `| \`${r.id}\` | ${r.severity} | ${escapeCell(r.description)} | ${sources} |\n`;
	}
	out += "\n";
}

writeFileSync(new URL("../docs/diagnostics.md", import.meta.url), out);
console.log(`Wrote ${ROOT}docs/diagnostics.md: ${RULES.length} rules.`);
