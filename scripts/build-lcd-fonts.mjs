#!/usr/bin/env node
/**
 * Generates src/display/lcdFontData.ts from RepRapFirmware's own 12864 font tables
 * (`src/Display/Lcd/Fonts/glcd7x11.cpp`, `glcd11x14.cpp` - "Liberation Sans" rendered with
 * MikroElektronika GLCD Font Creator; `Display.cpp`'s `fonts[] = { &font7x11, &font11x14 }` is the whole
 * font list on a 12864 display). The byte tables are copied verbatim (base64), the `LcdFont` header
 * fields are read from the same file, so the emulator draws the same glyphs at the same widths.
 *
 *   node scripts/build-lcd-fonts.mjs <path-to-RepRapFirmware-checkout>
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const rrf = process.argv[2];
if (!rrf) {
	console.error("usage: node scripts/build-lcd-fonts.mjs <RepRapFirmware checkout>");
	process.exit(2);
}
const dir = join(rrf, "src", "Display", "Lcd", "Fonts");

function parse(file, symbol, structName) {
	const src = readFileSync(join(dir, file), "utf8");
	const table = new RegExp("const uint8_t " + symbol + String.raw`\[\]\s*=\s*\{([\s\S]*?)\};`).exec(src);
	if (!table) throw new Error(`${symbol} not found in ${file}`);
	const bytes = [...table[1].replace(/\/\/[^\n]*/g, "").matchAll(/0x([0-9A-Fa-f]{2})/g)].map((m) => parseInt(m[1], 16));
	const header = new RegExp("LcdFont " + structName + String.raw`\s*=\s*\{([\s\S]*?)\};`).exec(src);
	if (!header) throw new Error(`${structName} not found in ${file}`);
	// Drop comments and the leading table identifier (its "7x11" would otherwise read as numbers).
	const nums = [...header[1].replace(/\/\/[^\n]*/g, "").replace(/^\s*[A-Za-z_]\w*,/, "").matchAll(/(0x[0-9A-Fa-f]+|\d+)/g)].map((m) => Number(m[1]));
	// nums: startCharacter, endCharacter, height, width, numSpaces
	const [startCharacter, endCharacter, height, width, numSpaces] = nums;
	const bytesPerChar = Math.ceil(height / 8) * width + 1;
	const expected = (endCharacter - startCharacter + 1) * bytesPerChar;
	if (bytes.length !== expected) throw new Error(`${file}: ${bytes.length} bytes, expected ${expected}`);
	return { startCharacter, endCharacter, height, width, numSpaces, data: Buffer.from(bytes).toString("base64") };
}

const fonts = [
	["FONT_7X11", parse("glcd7x11.cpp", "Liberation_Sans7x11", "font7x11")],
	["FONT_11X14", parse("glcd11x14.cpp", "Liberation_Sans11x14", "font11x14")],
];

let out = `/**
 * GENERATED by scripts/build-lcd-fonts.mjs from RepRapFirmware ${process.argv[3] ?? "3.7.0-rc.2"}
 * (src/Display/Lcd/Fonts/glcd7x11.cpp, glcd11x14.cpp) - do not edit by hand.
 *
 * Each font is RRF's own \`LcdFont\` table: per character one byte of active width, then \`width\`
 * columns of \`ceil(height / 8)\` little-endian bytes, least significant bit at the top.
 */

export interface LcdFontData {
	/** Unicode code point of the first character in the table. */
	startCharacter: number;
	/** Unicode code point of the last character in the table. */
	endCharacter: number;
	/** Row height in pixels. */
	height: number;
	/** Maximum character width in pixels (the table holds this many columns per character). */
	width: number;
	/** Space columns between characters before kerning. */
	numSpaces: number;
	/** Base64 of the raw table. */
	data: string;
}
`;
for (const [name, f] of fonts) {
	out += `\nexport const ${name}: LcdFontData = {\n\tstartCharacter: ${f.startCharacter},\n\tendCharacter: ${f.endCharacter},\n\theight: ${f.height},\n\twidth: ${f.width},\n\tnumSpaces: ${f.numSpaces},\n\tdata: "${f.data}",\n};\n`;
}
writeFileSync(new URL("../src/display/lcdFontData.ts", import.meta.url), out);
console.log("wrote src/display/lcdFontData.ts");
