#!/usr/bin/env node
/**
 * Builds `src/pins/communityBoards.ts` (`COMMUNITY_BOARD_PIN_TABLES`) from every `rrfpins.txt` file
 * in the gloomyandy/RRFBuild repo (task 17, `docs/tasks/17-pin-names-and-validation.md`, Part B,
 * Decision 6) - the real, per-board pin list the "TGBTC" (Team Gloomy BTC) STM32 firmware fork loads
 * at boot, one file per community board (BTT/FLY/Formbot/FYSETC/LDO).
 *
 * Each `rrfpins.txt` line is `<port.pin> alias1[,alias2,...]` (e.g. `F.3 bedtemp,tb`). A physical pin
 * (the same `port.pin`) can legitimately appear on more than one line under different, unrelated alias
 * groups (task 17's Findings - `octopuspro1_1_h723`'s `A.5`/`A.6`/`A.7` are both the display header
 * pins AND the general SPI bus pins) - this script merges those into one `PinTableEntry` per
 * `port.pin`, unioning their aliases, so two different alias spellings for the same wire resolve to
 * the same `canonicalName`.
 *
 * Reads the LOCAL `RRFBuild` clone (`C:\Users\live\Documents\Github\RRFBuild`) read-only, via
 * `git show`/`git ls-tree` at a fixed ref only - NEVER checks out, resets or touches the working tree,
 * since it's the user's own active clone with its own uncommitted work (a different branch than the
 * one this script reads).
 *
 *   node scripts/build-pin-tables-rrfpins.mjs [--ref upstream/v3.7-dev] [--clone <path>]
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT_TS = join(ROOT, "src", "pins", "communityBoards.ts");
const DEFAULT_CLONE = "C:\\Users\\live\\Documents\\Github\\RRFBuild";
const DEFAULT_REF = "upstream/v3.7-dev";

function git(clone, args) {
	return execFileSync("git", ["-C", clone, ...args], { encoding: "utf-8", maxBuffer: 64 * 1024 * 1024 });
}

/** One `PinTableEntry` per distinct `port.pin`, aliases unioned across every line that names it - see
 *  this file's own doc comment for why that merge is necessary (the `A.5`/`A.6`/`A.7` case). */
function parseRrfPinsFile(text) {
	const byId = new Map();
	for (const rawLine of text.split("\n")) {
		const line = rawLine.trim();
		if (line.length === 0) continue;
		const spaceIndex = line.indexOf(" ");
		if (spaceIndex < 0) continue; // not a "<id> <aliases>" line - skip defensively, don't guess
		const canonicalName = line.slice(0, spaceIndex).trim();
		const aliasesText = line.slice(spaceIndex + 1).trim();
		const aliases = aliasesText.split(",").map((a) => a.trim()).filter((a) => a.length > 0);
		let entry = byId.get(canonicalName);
		if (entry === undefined) {
			entry = [];
			byId.set(canonicalName, entry);
		}
		for (const a of aliases) if (!entry.includes(a)) entry.push(a);
	}
	return [...byId.entries()]
		.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
		.map(([canonicalName, aliases]) => ({ canonicalName, aliases }));
}

function buildTables(clone, ref) {
	const files = git(clone, ["ls-tree", "-r", "--name-only", ref, "--", "boards/"])
		.split("\n").map((l) => l.trim())
		.filter((l) => l.endsWith("/rrfpins.txt"));
	if (files.length === 0) {
		throw new Error(`No rrfpins.txt files found under boards/ at ${ref} in ${clone} - wrong clone/ref?`);
	}
	return files.map((path) => {
		const text = git(clone, ["show", `${ref}:${path}`]);
		const boardId = path.replace(/^boards\//, "").replace(/\/rrfpins\.txt$/, "");
		return {
			boardId,
			family: "rrfpins-txt",
			pins: parseRrfPinsFile(text),
			sources: [`gloomyandy/RRFBuild ${ref} ${path}`],
		};
	}).sort((a, b) => (a.boardId < b.boardId ? -1 : a.boardId > b.boardId ? 1 : 0));
}

function main() {
	const argv = process.argv.slice(2);
	let clone = DEFAULT_CLONE, ref = DEFAULT_REF;
	for (let i = 0; i < argv.length; i++) {
		if (argv[i] === "--clone") clone = argv[++i];
		else if (argv[i] === "--ref") ref = argv[++i];
	}

	const tables = buildTables(clone, ref);
	const totalPins = tables.reduce((n, t) => n + t.pins.length, 0);

	const header = `/**
 * Community-board (STM32 "TGBTC" firmware fork) pin tables - GENERATED by
 * \`scripts/build-pin-tables-rrfpins.mjs\` from every \`rrfpins.txt\` in the gloomyandy/RRFBuild repo.
 * Do not hand-edit; edit the source repo (or this script) and re-run it. See
 * \`docs/tasks/17-pin-names-and-validation.md\` (Part B).
 */

import type { BoardPinTable } from "./schema.js";

export const COMMUNITY_BOARD_PIN_TABLES: ReadonlyArray<BoardPinTable> = Object.freeze(
${JSON.stringify(tables, null, "\t")}
);
`;
	mkdirSync(join(ROOT, "src", "pins"), { recursive: true });
	writeFileSync(OUT_TS, header);
	console.log(`Wrote ${OUT_TS}: ${tables.length} boards, ${totalPins} pins total.`);
}

main();
